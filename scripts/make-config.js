#!/usr/bin/env node
// Build-time config: writes config.js from env (FORM_API_URL, FORM_KEY, optional FORM_ORIGIN). Never prints the values.
'use strict';
const fs = require('fs'), path = require('path');
const url = process.env.FORM_API_URL, key = process.env.FORM_KEY, origin = process.env.FORM_ORIGIN || 'https://kwentoperations.github.io';
if (!url || !/^https:\/\/script\.google\.com\/macros\/s\/[A-Za-z0-9_-]+\/exec$/.test(url)) { console.error('FORM_API_URL missing or not an Apps Script /exec URL'); process.exit(1); }
if (!key || !/^fk-[A-Za-z0-9]{8,64}$/.test(key)) { console.error('FORM_KEY missing or bad shape (expected fk-...)'); process.exit(1); }
const out = process.argv[2] || path.join(__dirname, '..', 'config.js');
fs.writeFileSync(out, '/* GENERATED by scripts/make-config.js. Do not commit. */\nwindow.SBX_CONFIG = ' + JSON.stringify({ apiUrl: url, formKey: key, origin }, null, 2) + ';\n');
console.log('wrote ' + out + ' (values not shown)');
